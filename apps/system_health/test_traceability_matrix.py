class TracerFixtures(TestCase):
    """Each of these does exactly one traceable thing, and says what."""

    def test_fixture_makes_one_http_request(self):
        # A 404 still goes through the handler, so this needs no real route and
        # cannot break when routing changes.
        response = self.client.get("/__traceability_control__")
        self.assertEqual(response.status_code, 404)

    def test_fixture_writes_one_model(self):
        from apps.audit.models import AuditLog
        from apps.audit.services import log as audit_log

        audit_log(
            action="traceability.control",
            subject_kind="Control",
            subject_id="tracer",
        )
        # log() is best-effort and swallows its own failures, so the fixture
        # has to check. Without this a swallowed write would reach the control
        # as "the tracer saw nothing", and the control would blame the tracer.
        self.assertEqual(
            AuditLog.objects.filter(action="traceability.control").count(),
            1,
            "the control's own write did not land, so it can prove nothing "
            "about the tracer",
        )

    def test_fixture_checks_one_permission(self):
        from apps.core.permissions import has_permission

        class _Nobody:
            active_role = None
            is_authenticated = True

        self.assertFalse(has_permission(_Nobody(), "traceability.controlPermission"))

    def test_fixture_fails_on_purpose(self):
        self.fail("this fixture exists to prove a red test is never traced")



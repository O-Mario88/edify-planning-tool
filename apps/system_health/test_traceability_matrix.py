class TracerControlsTest(SimpleTestCase):
    """A SimpleTestCase on purpose.

    The tracer runs a real ``django.test.TestCase``, and that class closes every
    connection in ``tearDownClass``. Nested inside another ``TestCase`` it takes
    the outer test's transaction down with it -- "the connection is closed",
    every control red, and the tracer blamed for it. A ``SimpleTestCase`` opens
    no transaction of its own, so the fixture's own rollback is the only
    cleanup needed and there is nothing for it to break.
    """

    databases = "__all__"

    def test_it_sees_an_http_route(self):
        recording = trace_test(_CONTROL + "test_fixture_makes_one_http_request")
        self.assertIn("GET /__traceability_control__", recording.routes)

    def test_it_sees_a_model_write(self):
        recording = trace_test(_CONTROL + "test_fixture_writes_one_model")
        self.assertIn("audit.AuditLog", recording.models_written)

    def test_it_sees_the_audit_action_that_write_recorded(self):
        recording = trace_test(_CONTROL + "test_fixture_writes_one_model")
        self.assertIn("traceability.control", recording.audit_actions)

    def test_it_sees_a_permission_check(self):
        recording = trace_test(_CONTROL + "test_fixture_checks_one_permission")
        self.assertIn("traceability.controlPermission", recording.permissions)

    def test_it_sees_the_service_file_that_ran(self):
        recording = trace_test(_CONTROL + "test_fixture_writes_one_model")
        self.assertIn("apps/audit/services.py", recording.services)

    def test_it_never_traces_a_failing_test(self):
        with self.assertRaises(TestPointerError):
            trace_test(_CONTROL + "test_fixture_fails_on_purpose")

    def test_it_refuses_a_pointer_that_names_nothing(self):
        with self.assertRaises(TestPointerError):
            trace_test(
                "apps.system_health.test_traceability_matrix:TracerFixtures."
                "test_no_such_fixture"
            )

    def test_it_leaves_no_trace_hook_behind(self):
        import sys

        before = sys.gettrace()
        trace_test(_CONTROL + "test_fixture_checks_one_permission")
        self.assertIs(sys.gettrace(), before)

    def test_it_ignores_the_test_that_drives_it(self):
        """The harness must not appear in the evidence it collects."""
        recording = trace_test(_CONTROL + "test_fixture_writes_one_model")
        self.assertNotIn(
            "apps/system_health/test_traceability_matrix.py", recording.services
        )
        self.assertNotIn("apps/system_health/traceability.py", recording.services)


class InstrumentationIsReversibleTest(SimpleTestCase):
    def test_signals_are_disconnected_afterwards(self):
        from django.db.models.signals import post_save

        before = len(post_save.receivers)
        with Instrumentation():
            during = len(post_save.receivers)
        self.assertGreater(during, before)
        self.assertEqual(len(post_save.receivers), before)



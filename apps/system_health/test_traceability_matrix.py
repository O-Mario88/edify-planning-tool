"""Hold the committed traceability matrix to reality, and prove the tracer looks.

Two different failures are possible here and they need different guards.

The first is drift: the matrix is generated by a command nobody runs on every
commit, so the committed artefact can fall behind the journeys it claims to
describe. ``ManifestMatchesTheJourneysTest`` compares it against
``apps.core.tests.release_journeys`` -- the same manifest the journey census
holds -- so a renamed test or a newly covered journey turns the artefact stale
loudly rather than quietly.

The second is worse, and it is the one this audit has hit four times already: a
tool built to find defects producing one of its own. A tracer that records
nothing produces a matrix full of honest-looking zeroes, and a zero reads
exactly like "the platform does not do this". So ``TracerControlsTest`` runs the
tracer against known-answer tests in this very module -- one that makes an HTTP
request, one that writes a model, one that checks a permission, one that fails
on purpose -- and asserts it saw each. If the tracer stops seeing, these go red
before any conclusion is drawn from a zero.

The zero that matters is pinned separately, in ``TheJourneysNeverKnockTest``.
"""

from __future__ import annotations

import json
import unittest
from pathlib import Path

from django.conf import settings
from django.test import SimpleTestCase, TestCase

from apps.core.tests.release_journeys import JOURNEYS
from apps.system_health.traceability import (
    Instrumentation,
    Recording,
    TestPointerError,
    _metrics_for,
    normalise_route,
    split_service_path,
    trace_test,
)

MATRIX_PATH = Path(settings.BASE_DIR) / "docs" / "platform-traceability-matrix.json"

#: Requirements traced by executing their own test. Matches COVERED_COUNT in
#: apps/core/tests/test_release_journey_census.py -- deliberately restated
#: rather than imported, so that adding a journey test forces a look at both
#: the census and this artefact instead of one silently satisfying the other.
TRACED_COUNT = 20

#: Requirements with no test to trace: the two journeys blocked on capability
#: that was never built.
UNTRACED_COUNT = 2

_CONTROL = "apps.system_health.test_traceability_matrix:TracerFixtures."


def load_matrix() -> dict:
    return json.loads(MATRIX_PATH.read_text(encoding="utf-8"))



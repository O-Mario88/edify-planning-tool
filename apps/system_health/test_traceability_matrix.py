class RouteNormalisationTest(SimpleTestCase):
    """Opaque ids out, route words kept.

    Both halves matter. Leaving fixture ids in makes the committed artefact
    differ from itself on every rebuild, and a matrix that churns without the
    platform changing teaches its readers to skip its diffs. Normalising too
    eagerly is worse the other way: two genuinely different routes would
    collapse into one and the door coverage would be overstated.
    """

    def test_it_replaces_a_cuid(self):
        self.assertEqual(
            normalise_route("/schools/cmt9slehb0050amdjhi8o/edit-drawer"),
            "/schools/{id}/edit-drawer",
        )

    def test_it_replaces_a_uuid(self):
        self.assertEqual(
            normalise_route("/apps/8f8682cd-1111-2222-3333-444455556666/spec"),
            "/apps/{id}/spec",
        )

    def test_it_replaces_a_bare_integer(self):
        self.assertEqual(normalise_route("/reports/2026/"), "/reports/{id}/")

    def test_it_keeps_route_words(self):
        for path in (
            "/disbursements",
            "/fund-requests/weekly/xr-no-such-request/disburse",
            "/core-schools/schedule-visit/action",
            "/accounts/partner-payments/xr-no-such-activity/pay",
        ):
            with self.subTest(path=path):
                self.assertEqual(normalise_route(path), path)

    def test_it_is_stable_under_repetition(self):
        once = normalise_route("/schools/cmt9slehb0050amdjhi8o/edit-drawer")
        self.assertEqual(normalise_route(once), once)


class MetricAttributionTest(SimpleTestCase):
    """Prove the metric join before reading anything into an empty metric cell.

    The matrix credits no journey with computing a registered metric. That is
    either a real property of the journey evidence or a broken join, and the
    two are indistinguishable from the artefact alone. These three tests
    separate them: the tracer records functions and not merely files, a metric
    whose own computing function ran is credited, and a metric whose module ran
    without it is not. The last is the regression pin for the first version of
    this module, which matched on the file and credited one journey with twelve
    analytics metrics it had never computed.
    """

    databases = "__all__"

    def _first_spec(self):
        from apps.core.metrics.registry import all_metrics

        return sorted(all_metrics(), key=lambda spec: spec.key)[0]

    def test_the_tracer_records_functions_not_just_files(self):
        recording = trace_test(_CONTROL + "test_fixture_writes_one_model")
        self.assertIn("apps/audit/services.py::log", recording.functions)

    def test_a_metric_is_credited_when_its_own_function_ran(self):
        spec = self._first_spec()
        module_file, function_name = split_service_path(spec.service)
        recording = Recording(functions={f"{module_file}::{function_name}"})
        computed, _ = _metrics_for(recording)
        self.assertIn(spec.key, computed)

    def test_a_metric_is_not_credited_when_only_its_module_ran(self):
        spec = self._first_spec()
        module_file, function_name = split_service_path(spec.service)
        recording = Recording(
            services={module_file},
            functions={f"{module_file}::some_other_function_entirely"},
        )
        computed, _ = _metrics_for(recording)
        self.assertNotIn(spec.key, computed)

    def test_a_metric_is_affected_when_a_source_model_is_written(self):
        from apps.core.metrics.registry import all_metrics

        spec = next(spec for spec in all_metrics() if spec.source_models)
        recording = Recording(models_written={spec.source_models[0]})
        _, affected = _metrics_for(recording)
        self.assertIn(spec.key, affected)



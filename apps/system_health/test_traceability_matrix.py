def _flatten(suite):
    for item in suite:
        if isinstance(item, unittest.TestSuite):
            yield from _flatten(item)
        else:
            yield item


def load_tests(loader, standard_tests, pattern):
    """Keep the tracer fixtures out of the normal suite.

    ``TracerFixtures.test_fixture_fails_on_purpose`` must genuinely fail — that
    failure is how ``test_it_never_traces_a_failing_test`` proves the tracer
    refuses to record evidence from a red test. Discovered normally it would
    turn the build red for the wrong reason, so discovery skips the whole
    fixture class; ``TracerControlsTest`` runs each fixture itself, through the
    tracer, which is where their result actually means something.
    """
    kept = unittest.TestSuite()
    for test in _flatten(standard_tests):
        if isinstance(test, TracerFixtures):
            continue
        kept.addTest(test)
    return kept

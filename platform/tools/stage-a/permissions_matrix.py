"""Stage A (docs/migration/177): the route-by-role permissions matrix.

    python manage.py shell < platform/tools/stage-a/permissions_matrix.py

For every full page in docs/platform-page-inventory.json, whether each role
may open it (apps.core.permissions.can_open_url, the same gate the site and
the feed ask), and the same for an Acting Program Lead and an Acting Country
Director (the acting role's pages less those apps.acting.policy leaves with
the substantive leader). It reads the permission rules only; nothing is
written to any database. Writes docs/migration/179-stage-a/permissions-matrix
.md and .csv.
"""

import csv
import io
import json
import re
from datetime import date
from pathlib import Path

from apps.acting import policy
from apps.core.acting import CONTEXT_ATTR, ActingContext
from apps.core.permissions import can_open_url
from apps.core.rbac import EdifyRole
from apps.schools.management.commands.export_school_directory_rules import (
    _role_user,
)

OUT = Path("docs/migration/179-stage-a")
PARAM = re.compile(r"<[^>]+>")

#: Short column names, in the order the roles are listed.
SHORT = {
    "CCEO": "CCEO",
    "Program Lead": "PL",
    "CountryDirector": "CD",
    "ImpactAssessment": "IA",
    "Accountant": "Acct",
    "RegionalVicePresident": "RVP",
    "RegionalProgramLead": "RPL",
    "HumanResources": "HR",
    "BusinessTransformationOfficer": "BT",
    "ProjectCoordinator": "PC",
    "Admin": "Admin",
    "PartnerAdmin": "PartnerAdm",
    "PartnerFieldOfficer": "PartnerFO",
    "MfiPartnerAdmin": "LenderAdm",
    "MfiLoanOfficer": "LoanOff",
    "ClusterLeader": "ClusterLdr",
}


def acting(entry):
    """A principal in its acting capacity: the acting role, less what the
    appointment withholds."""
    user = _role_user(entry.acting_role_value)
    context = ActingContext(
        assignment_id="stage-a",
        acting_role=entry.acting_role_value,
        substantive_role=entry.appointee_role.value,
        label=entry.label,
        short_label=entry.short_label,
        scope_type=entry.scope_type,
        seat_staff_id="",
        seat_user_id="",
        seat_name="",
        country="",
        start_date=date.today(),
        end_date=date.today(),
        appointed_by_id="",
        appointed_by_name="",
        withheld_permissions=entry.withheld_permission_values(),
        withheld_pages=entry.withheld_pages,
        withheld_authorities=frozenset(),
    )
    setattr(user, CONTEXT_ATTR, context)
    return user


inventory = json.loads(
    Path("docs/platform-page-inventory.json").read_text(encoding="utf-8")
)
routes = sorted(
    {
        "/" + p["route"].strip("/")
        for p in inventory["pages"]
        if p.get("surface_kind") == "page" and p.get("route") is not None
    }
)
readers = [(SHORT.get(r.value, r.value), _role_user(r.value)) for r in EdifyRole]
readers += [
    ("Acting PL", acting(policy.ACTING_PROGRAM_LEAD)),
    ("Acting CD", acting(policy.ACTING_COUNTRY_DIRECTOR)),
]
rows = []
for route in routes:
    path = PARAM.sub("0", route)
    opens = []
    for _, user in readers:
        try:
            opens.append(bool(can_open_url(user, path)))
        except Exception:  # noqa: BLE001 - a route the gate cannot ask is unknown
            opens.append(None)
    rows.append((route, opens))

OUT.mkdir(parents=True, exist_ok=True)
names = [name for name, _ in readers]
buffer = io.StringIO()
writer = csv.writer(buffer)
writer.writerow(["route", *names])
for route, opens in rows:
    writer.writerow([route, *("" if o is None else int(o) for o in opens)])
(OUT / "permissions-matrix.csv").write_text(buffer.getvalue(), encoding="utf-8")

mark = {True: "●", False: "·", None: "?"}
lines = [
    "# Route-by-role permissions matrix (Stage A)",
    "",
    "Generated by `platform/tools/stage-a/permissions_matrix.py` from the",
    "permission rules in the code (`can_open_url`), not from screenshots: ● opens,",
    "· refused, ? the gate could not be asked for that route without a record.",
    "An opened page may still narrow what it shows to the reader's scope.",
    f"{len(routes)} full pages × {len(names)} readers.",
    "",
    "| Route | " + " | ".join(names) + " |",
    "|---|" + "---|" * len(names),
]
for route, opens in rows:
    lines.append(f"| `{route}` | " + " | ".join(mark[o] for o in opens) + " |")
totals = [sum(1 for _, opens in rows if opens[i]) for i in range(len(names))]
lines += ["", "| Pages each reader opens | " + " | ".join(map(str, totals)) + " |", ""]
(OUT / "permissions-matrix.md").write_text("\n".join(lines), encoding="utf-8")
print(f"{len(routes)} routes, {len(names)} readers")
print(dict(zip(names, totals)))

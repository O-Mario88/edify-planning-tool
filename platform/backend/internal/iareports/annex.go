// ErrNoAnnex is the view's 404: the annex is not the reader's.
var ErrNoAnnex = errors.New("The evidence annex is not available to you.")

// rowKeys are reports.ROW_KEYS.
var rowKeys = iapages.RowKeys

// exportRoles may export (RolePermissionService.can_export).
var exportRoles = []string{"Accountant", "Admin", "BusinessTransformationOfficer", "CountryDirector", "ImpactAssessment",
	"Program Lead", "ProjectCoordinator", "RegionalProgramLead", "RegionalVicePresident"}

// csvValue is reports.csv_value then spreadsheet_text, over a value read
// from the stored snapshot.
func csvValue(v any) string { return iapages.CSVCell(v) }

// jsonbKeys are an object's keys in the order PostgreSQL's jsonb keeps
// them, which is the order Django reads them back in: shorter first, then
// bytewise.
func jsonbKeys(m map[string]any) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool {
		if len(keys[i]) != len(keys[j]) {
			return len(keys[i]) < len(keys[j])
		}
		return keys[i] < keys[j]
	})
	return keys
}

// Annex is annex_download: the CSV file and its name, audited.
func (r Reports) Annex(ctx context.Context, p auth.Principal, id string) (string, []byte, error) {
	x, err := r.visible(ctx, r.DB, p, id, false)
	if err != nil {
		return "", nil, err
	}
	if x == nil {
		return "", nil, ErrNoAnnex
	}
	role := p.ActiveRole
	if x.status == statusDraft || role == "RegionalVicePresident" || !(role == roleIA || role == "CountryDirector" || role == "Admin") ||
		!slices.Contains(exportRoles, role) {
		return "", nil, ErrNoAnnex
	}
	var raw []byte
	var hash string
	if err := r.DB.QueryRow(ctx, `SELECT evidence_snapshot::text, snapshot_hash FROM impact_report WHERE id = $1`, id).Scan(&raw, &hash); err != nil {
		return "", nil, fmt.Errorf("iareports: the frozen evidence: %w", err)
	}
	d := json.NewDecoder(bytes.NewReader(raw))
	d.UseNumber()
	var snapshot map[string]any
	if err := d.Decode(&snapshot); err != nil {
		return "", nil, fmt.Errorf("iareports: reading the frozen evidence: %w", err)
	}
	var name string
	_ = r.DB.QueryRow(ctx, `SELECT COALESCE(name, '') FROM "user" WHERE id = $1`, p.UserID).Scan(&name)
	now := r.now()
	cohort, _ := snapshot["cohort"].(map[string]any)
	portfolio, _ := snapshot["portfolio"].(map[string]any)
	get := func(m map[string]any, k string) any { return m[k] }
	rows := [][]any{
		{"Impact Assessment evidence annex", fmt.Sprintf("Version %d", x.version)},
		{"Report", x.title}, {"Status", statusLabels[x.status]}, {"Country", x.country},
		{"Period", iapages.PeriodLabel(x.fy, x.start, x.end)}, {"Evidence frozen at", orEmpty(snapshot["generated_at"])},
		{"Snapshot sha256", hash}, {"Generated by", name}, {"Generated by role", role},
		{"Generated at", pyISO(now)}, {"Counting unit", "Project-school enrolments, not unique schools"},
		{"Limitation", orEmpty(snapshot["limitation"])}, {}, {"Project cohort", "Value"},
	}
	for _, k := range jsonbKeys(cohort) {
		rows = append(rows, []any{k, cohort[k]})
	}
	if len(portfolio) > 0 {
		rows = append(rows, []any{}, []any{fmt.Sprintf("School change FY%s to FY%s", pyText(portfolio["prev_fy"]), pyText(portfolio["fy"])),
			"Schools measured", "Improved %", "Declined %", "Median change", "Evidence"})
		for _, raw := range list(portfolio["rows"]) {
			row, _ := raw.(map[string]any)
			grade, _ := row["grade"].(map[string]any)
			rows = append(rows, []any{get(row, "name"), get(row, "n"), get(row, "improved_pct"), get(row, "declined_pct"),
				get(row, "median_change"), orEmpty(grade["label"])})
		}
	}
	rows = append(rows, []any{}, []any{"Mapping version", "SSA domain", "Enrolments"})
	for _, raw := range list(snapshot["mapping_versions"]) {
		m, _ := raw.(map[string]any)
		rows = append(rows, []any{m["mapping_version"], m["intervention"], m["enrolments"]})
	}
	lending, _ := snapshot["lending"].(map[string]any)
	ids := list(lending["verified_ids"])
	rows = append(rows, []any{}, []any{"Verified loan impact conclusions", len(ids)})
	for _, ref := range ids {
		rows = append(rows, []any{"Loan conclusion id", ref})
	}
	header := []any{}
	for _, k := range rowKeys {
		header = append(header, k)
	}
	rows = append(rows, []any{}, header)
	evidenceRows := list(snapshot["rows"])
	for _, raw := range evidenceRows {
		row, _ := raw.(map[string]any)
		line := []any{}
		for _, k := range rowKeys {
			line = append(line, row[k])
		}
		rows = append(rows, line)
	}
	var out bytes.Buffer
	w := csv.NewWriter(&out)
	w.UseCRLF = true
	for _, row := range rows {
		cells := make([]string, len(row))
		for i, v := range row {
			cells[i] = csvValue(v)
		}
		if err := w.Write(cells); err != nil {
			return "", nil, err
		}
	}
	w.Flush()
	err = pgx.BeginTxFunc(ctx, r.DB, pgx.TxOptions{AccessMode: pgx.ReadWrite}, func(tx pgx.Tx) error {
		_, err := audit.Append(ctx, tx, reportAudit("ia.report.annex_downloaded", id, p, x.country, x.version, x.status, hash,
			map[string]any{"rows": len(evidenceRows)}), now)
		return err
	})
	if err != nil {
		return "", nil, err
	}
	return fmt.Sprintf("impact-report-%s-v%d-annex.csv", id, x.version), out.Bytes(), nil
}

func list(v any) []any {
	l, _ := v.([]any)
	return l
}

func orEmpty(v any) string {
	if v == nil {
		return ""
	}
	return pyText(v)
}

func pyText(v any) string {
	if n, ok := v.(json.Number); ok {
		return n.String()
	}
	if v == nil {
		return "None"
	}
	return fmt.Sprint(v)
}

// pyISO is datetime.isoformat() of an aware UTC moment.
func pyISO(t time.Time) string {
	t = t.UTC()
	if t.Nanosecond()/1000 == 0 {
		return t.Format("2006-01-02T15:04:05+00:00")
	}
	return t.Format("2006-01-02T15:04:05.000000+00:00")
}

// releaseRow is one row of release_rows' walk.
type releaseRow []any

// walkRelease is release_rows' walk: every leaf of the payload as Section /
// Measure / Value, objects in the order Django reads them back.
func walkRelease(section string, value any, rows *[]releaseRow) {
	switch x := value.(type) {
	case map[string]any:
		for _, k := range jsonbKeys(x) {
			next := k
			if section != "" {
				next = section + "." + k
			}
			walkRelease(next, x[k], rows)
		}
	case []any:
		for i, inner := range x {
			walkRelease(fmt.Sprintf("%s[%d]", section, i+1), inner, rows)
		}
	default:
		head, measure := "", section
		if i := strings.LastIndex(section, "."); i >= 0 {
			head, measure = section[:i], section[i+1:]
		}
		if head == "" {
			head = section
		}
		if measure == "" {
			measure = section
		}
		*rows = append(*rows, releaseRow{head, measure, value})
	}
}

// ReleaseDownload is release_download: a released donor or school version
// as Section / Measure / Value rows; the leadership version is the annex.
func (r Reports) ReleaseDownload(ctx context.Context, p auth.Principal, reportID, releaseID string) (string, []byte, error) {
	x, err := r.visible(ctx, r.DB, p, reportID, false)
	if err != nil {
		return "", nil, err
	}
	if x == nil {
		return "", nil, ErrNoAnnex
	}
	var audience, status string
	var released *time.Time
	var raw []byte
	err = r.DB.QueryRow(ctx, `SELECT audience, status, released_at, rendered_payload::text FROM impact_report_release
WHERE id = $1 AND report_id = $2`, releaseID, reportID).Scan(&audience, &status, &released, &raw)
	if errors.Is(err, pgx.ErrNoRows) {
		return "", nil, ErrNoAnnex
	}
	if err != nil {
		return "", nil, fmt.Errorf("iareports: the release: %w", err)
	}
	if (p.ActiveRole == "RegionalVicePresident" && audience != "donor") || status != "released" || !slices.Contains(exportRoles, p.ActiveRole) {
		return "", nil, ErrNoAnnex
	}
	if audience == "leadership" {
		return r.Annex(ctx, p, reportID)
	}
	d := json.NewDecoder(bytes.NewReader(raw))
	d.UseNumber()
	var payload map[string]any
	if err := d.Decode(&payload); err != nil {
		return "", nil, fmt.Errorf("iareports: reading the release: %w", err)
	}
	var hash string
	_ = r.DB.QueryRow(ctx, `SELECT snapshot_hash FROM impact_report WHERE id = $1`, reportID).Scan(&hash)
	at := ""
	if released != nil {
		at = pyISO(*released)
	}
	label := map[string]string{"leadership": "Country leadership", "school": "Partner school", "donor": "Donors"}[audience]
	rows := []releaseRow{{"Impact report", label}, {"Released at", at}, {"Report version", x.version}, {"Snapshot sha256", hash}, {},
		{"Section", "Measure", "Value"}}
	walkRelease("", payload, &rows)
	var out bytes.Buffer
	w := csv.NewWriter(&out)
	w.UseCRLF = true
	for _, row := range rows {
		cells := make([]string, len(row))
		for i, v := range row {
			cells[i] = csvValue(v)
		}
		if err := w.Write(cells); err != nil {
			return "", nil, err
		}
	}
	w.Flush()
	now := r.now()
	err = pgx.BeginTxFunc(ctx, r.DB, pgx.TxOptions{AccessMode: pgx.ReadWrite}, func(tx pgx.Tx) error {
		_, err := audit.Append(ctx, tx, reportAudit("ia.report.release_downloaded", reportID, p, x.country, x.version, x.status, hash,
			map[string]any{"release_id": releaseID, "audience": audience}), now)
		return err
	})
	if err != nil {
		return "", nil, err
	}
	return fmt.Sprintf("impact-report-%s-v%d-%s.csv", reportID, x.version, audience), out.Bytes(), nil
}

// LiveAnnex is impact_report_download: the live evidence annex for p,
// audited as the view audits it.
func (r Reports) LiveAnnex(ctx context.Context, p auth.Principal, query url.Values) (string, []byte, bool, error) {
	name, body, entry, handled, err := iapages.NewService(r.DB, r.now).LiveAnnexFile(ctx, p, query)
	if !handled || err != nil {
		return "", nil, handled, err
	}
	err = pgx.BeginTxFunc(ctx, r.DB, pgx.TxOptions{AccessMode: pgx.ReadWrite}, func(tx pgx.Tx) error {
		_, err := audit.Append(ctx, tx, entry, r.now())
		return err
	})
	if err != nil {
		return "", nil, true, fmt.Errorf("iareports: auditing the evidence annex: %w", err)
	}
	return name, body, true, nil
}

/**
 * Copies the existing web's design tokens into the Next.js app, so the two
 * are drawn from one palette and nothing is restated by hand.
 *
 *   assets/css/_theme.css            -> src/styles/generated/theme.css (verbatim)
 *   static/css/design-system.css     -> src/styles/generated/edify-tokens.css
 *     (every custom property and color-scheme of :root, :root.light and
 *      :root.theme-dark, with the @media blocks that wrap them)
 *   static/fonts/Geist-Variable.woff2 -> src/fonts/Geist-Variable.woff2
 *   static/images/logo.png, login-classroom-portrait.jpg -> public/images/
 *
 * `node scripts/sync-tokens.mjs` writes them; `--check` exits 1 when the
 * committed copies differ (the unit tests run the same check).
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const here = dirname(fileURLToPath(import.meta.url));
export const WEB = join(here, '..');
export const REPO = join(WEB, '..', '..');

/** The themes the web app offers: the existing light and dark themes. */
export const THEME_SELECTORS = new Set([':root', ':root.light', ':root.theme-dark']);

const HEADER = (source) =>
  `/* GENERATED by platform/web/scripts/sync-tokens.mjs from ${source}.\n` +
  '   Do not edit: change the existing web CSS, then run `npm run tokens`. */\n';

function keepRule(rule) {
  if (!THEME_SELECTORS.has(rule.selector.trim())) return false;
  const parent = rule.parent;
  if (parent.type === 'root') return true;
  return parent.type === 'atrule' && parent.name === 'media' && parent.parent.type === 'root';
}

/** The token layer of design-system.css, as CSS text. */
export function extractTokens(css) {
  const out = postcss.root();
  const tree = postcss.parse(css);
  tree.walkRules((rule) => {
    if (!keepRule(rule)) return;
    const copy = postcss.rule({ selector: rule.selector.trim() });
    rule.each((node) => {
      if (node.type === 'decl' && (node.prop.startsWith('--') || node.prop === 'color-scheme')) {
        copy.append(postcss.decl({ prop: node.prop, value: node.value.replace(/\s+/g, ' ').trim() }));
      }
    });
    if (!copy.nodes.length) return;
    if (rule.parent.type === 'atrule') {
      const media = postcss.atRule({ name: 'media', params: rule.parent.params });
      media.append(copy);
      out.append(media);
    } else {
      out.append(copy);
    }
  });
  out.raws.after = '\n';
  return out.toString();
}

export function expectedFiles() {
  const theme = readFileSync(join(REPO, 'assets/css/_theme.css'), 'utf8');
  const system = readFileSync(join(REPO, 'static/css/design-system.css'), 'utf8');
  return [
    ['src/styles/generated/theme.css', HEADER('assets/css/_theme.css') + theme],
    ['src/styles/generated/edify-tokens.css', HEADER('static/css/design-system.css') + extractTokens(system)],
    ['src/fonts/Geist-Variable.woff2', readFileSync(join(REPO, 'static/fonts/Geist-Variable.woff2'))],
    ['public/images/logo.png', readFileSync(join(REPO, 'static/images/logo.png'))],
    ['public/images/login-classroom-portrait.jpg', readFileSync(join(REPO, 'static/images/login-classroom-portrait.jpg'))],
  ];
}

/** The generated files that differ from what the existing web says. */
export function staleFiles() {
  return expectedFiles()
    .filter(([path, content]) => {
      try {
        return !Buffer.from(content).equals(readFileSync(join(WEB, path)));
      } catch {
        return true;
      }
    })
    .map(([path]) => path);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const stale = staleFiles();
    if (stale.length) {
      console.error(`Out of date with the existing web: ${stale.join(', ')}. Run npm run tokens.`);
      process.exit(1);
    }
  } else {
    for (const [path, content] of expectedFiles()) {
      mkdirSync(dirname(join(WEB, path)), { recursive: true });
      writeFileSync(join(WEB, path), content);
    }
  }
}

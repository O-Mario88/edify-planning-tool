/**
 * Writes the Edify Enterprise Design System's tokens (platform/design/
 * tokens.json) for both apps, so the web and the native app are drawn from
 * one source:
 *
 *   platform/web/src/styles/ds/tokens.css  -- CSS variables for the light and
 *     dark themes and a Tailwind v4 @theme that names them
 *   platform/mobile/src/ds/tokens.ts       -- the same values, typed
 *
 * Before writing it checks every text and status colour against the surfaces
 * it is drawn on (WCAG 2.2 contrast: 4.5 for text, 3 for focus) and refuses
 * tokens that fall short.
 *
 *   node platform/design/build-tokens.mjs           write both files
 *   node platform/design/build-tokens.mjs --check   exit 1 if either differs
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const PLATFORM = join(here, '..');
export const TOKENS = join(here, 'tokens.json');
export const WEB_OUT = join(PLATFORM, 'web', 'src', 'styles', 'ds', 'tokens.css');
export const MOBILE_OUT = join(PLATFORM, 'mobile', 'src', 'ds', 'tokens.ts');

const HEADER = 'GENERATED by platform/design/build-tokens.mjs from platform/design/tokens.json. Do not edit.';

/** WCAG relative luminance of a #rrggbb colour. */
export function luminance(hex) {
  const n = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(n.slice(i, i + 2), 16) / 255);
  const lin = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
}

export function contrast(a, b) {
  const [x, y] = [luminance(a), luminance(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}

/** The pairs a screen draws: [foreground, background, minimum]. */
const PAIRS = [
  ...['text', 'text-muted', 'text-subtle', 'primary', 'brand-ink'].flatMap((fg) =>
    ['bg', 'surface', 'surface-sunken', 'surface-raised', 'surface-selected'].map((bg) => [fg, bg, 4.5]),
  ),
  ['primary-ink', 'primary', 4.5],
  ['primary-ink', 'primary-hover', 4.5],
  ...['success', 'warning', 'danger', 'info'].flatMap((s) => [
    [s, `${s}-soft`, 4.5],
    [s, 'surface', 4.5],
  ]),
  ['focus', 'surface', 3],
  ['focus', 'bg', 3],
];

export function contrastReport(tokens) {
  const failures = [];
  const rows = [];
  for (const [theme, colors] of Object.entries(tokens.color)) {
    for (const [fg, bg, min] of PAIRS) {
      const ratio = contrast(colors[fg], colors[bg]);
      rows.push({ theme, fg, bg, ratio: Math.round(ratio * 100) / 100, min });
      if (ratio < min) failures.push(`${theme}: ${fg} on ${bg} is ${ratio.toFixed(2)}, needs ${min}`);
    }
  }
  return { rows, failures };
}

function cssVars(colors, indent = '  ') {
  return Object.entries(colors)
    .map(([name, value]) => `${indent}--ds-${name}: ${value};`)
    .join('\n');
}

export function renderCSS(tokens) {
  const { light, dark } = tokens.color;
  const theme = [
    ...Object.keys(light).map((name) => `  --color-ds-${name}: var(--ds-${name});`),
    ...Object.entries(tokens.text).flatMap(([name, t]) => [
      `  --text-ds-${name}: ${t.size}px;`,
      `  --text-ds-${name}--line-height: ${t.line}px;`,
    ]),
    ...Object.entries(tokens.radius).map(([name, v]) => `  --radius-ds-${name}: ${v}px;`),
    ...Object.entries(tokens.shadow).map(([name, v]) => `  --shadow-ds-${name}: ${v};`),
    ...Object.entries(tokens.space).map(([name, v]) => `  --spacing-ds-${name}: ${v}px;`),
    ...Object.entries(tokens.breakpoint)
      .filter(([name]) => name !== 'phone')
      .map(([name, v]) => `  --breakpoint-ds-${name}: ${v}px;`),
  ];
  return [
    `/* ${HEADER} */`,
    ':root {',
    cssVars(light),
    `  --ds-font-weight-medium: ${tokens.font.weight.medium};`,
    `  --ds-font-weight-semibold: ${tokens.font.weight.semibold};`,
    `  --ds-font-weight-bold: ${tokens.font.weight.bold};`,
    `  --ds-target: ${tokens.size.target}px;`,
    `  --ds-control: ${tokens.size.control}px;`,
    ...Object.entries(tokens.motion).map(([name, v]) => `  --ds-motion-${name}: ${v}ms;`),
    '}',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not(.light) {',
    cssVars(dark, '    '),
    '  }',
    '}',
    ':root.theme-dark {',
    cssVars(dark),
    '}',
    '@theme inline {',
    ...theme,
    '}',
    '',
  ].join('\n');
}

export function renderTS(tokens) {
  const body = JSON.stringify(
    {
      color: tokens.color,
      font: tokens.font,
      text: tokens.text,
      space: tokens.space,
      radius: tokens.radius,
      size: tokens.size,
      breakpoint: tokens.breakpoint,
      motion: tokens.motion,
    },
    null,
    2,
  );
  return [
    `// ${HEADER}`,
    `export const tokens = ${body} as const;`,
    '',
    'export type ColorName = keyof typeof tokens.color.light;',
    'export type ThemeName = keyof typeof tokens.color;',
    '',
  ].join('\n');
}

export function build() {
  const tokens = JSON.parse(readFileSync(TOKENS, 'utf8'));
  const { failures } = contrastReport(tokens);
  if (failures.length) throw new Error(`tokens fail contrast:\n${failures.join('\n')}`);
  return { css: renderCSS(tokens), ts: renderTS(tokens) };
}

function main() {
  const check = process.argv.includes('--check');
  const { css, ts } = build();
  const outputs = [
    [WEB_OUT, css],
    [MOBILE_OUT, ts],
  ];
  if (check) {
    const stale = outputs.filter(([file, text]) => !existsSync(file) || readFileSync(file, 'utf8') !== text);
    if (stale.length) {
      console.error(`stale: ${stale.map(([f]) => f).join(', ')}; run node platform/design/build-tokens.mjs`);
      process.exit(1);
    }
    return;
  }
  for (const [file, text] of outputs) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
  console.log(`wrote ${outputs.map(([f]) => f).join(' and ')}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
